"""Compile the explicit audition arrangement into sample-addressed C events."""
import argparse
import json
from pathlib import Path
import wave

ROOT = Path(__file__).resolve().parents[1]
RATE = 48000


def generate():
    score = json.loads((ROOT / 'music/prototype.json').read_text())
    with wave.open(str(ROOT / 'legacy/Content/Music' / (score['reference_duration'] + '.wav'))) as wav:
        frames = round(wav.getnframes() * RATE / wav.getframerate())
    step = 60 / score['bpm'] / 4
    events = []

    def note(time, duration, patch, pitch, velocity, pan=0):
        frame = round(time * RATE)
        if frame >= frames or duration <= 0:
            return
        assert 0 <= patch < 9 and 0 < pitch < 128 and 0 < velocity < 128 and -100 <= pan <= 100
        events.append((frame, max(1, round(duration * RATE)), patch, pitch, velocity, pan))

    previous_end = 0
    for section in score['sections']:
        start, end = section['start'], section['end']
        assert abs(start - previous_end) < .0001 and end > start
        previous_end = end
        i = 0
        while start + i * step < end - .000001:
            time = start + i * step
            bar, slot = i // 16, i % 16
            chord_index = bar % len(score['roots'])
            root = score['roots'][chord_index]
            chord = score['chords'][chord_index]
            gate = lambda duration: min(duration, end - time)
            if section['pad'] and slot == 0:
                for j, interval in enumerate(chord):
                    note(time, gate(step * 14), 4, root + 24 + interval, 60, (j - 1) * 45)
            if section['bass'] and slot in (0, 3, 6, 8, 10, 14):
                pitch = root + (12 if slot in (6, 14) else 7 if slot == 10 else 0)
                note(time, gate(step * (1.7 if slot in (0, 8) else .8)), 0, pitch, 100 if slot in (0, 8) else 83)
            if section['arp'] and slot % 2 == 0:
                interval = chord[(i // 2) % 3]
                note(time, gate(step * .8), 2, root + 36 + interval, 53 if section['lead'] else 76, -45)
            if section['lead'] and slot % 2 == 0:
                melody = score['melodies'][(bar // 4) % len(score['melodies'])]
                pitch = melody[(i // 2) % len(melody)]
                if pitch:
                    note(time, gate(step * 1.65), 1, pitch, 94 if slot in (0, 8) else 84, 16)
            if section['bells'] and slot in (0, 10) and (bar % 2 == 0 or not section['lead']):
                note(time, gate(step * 3), 3, root + 48 + chord[(bar + slot) % 3], 64, 55)
            drums = section['drums']
            if drums:
                if slot in ((0, 8) if drums < 3 else (0, 6, 8, 14)):
                    note(time, .24, 5, 36, 114 if slot in (0, 8) else 86)
                if drums >= 2 and slot in (4, 12):
                    note(time, .20, 6, 50, 100, -8)
                if drums >= 2 and slot % 2 == 0:
                    note(time, .075, 7, 92, 84 if slot % 4 == 0 else 57, 32)
                if drums == 3 and bar % 4 == 3 and slot in (13, 14, 15):
                    note(time, .23, 8, 52 - (slot - 13) * 3, 90, (slot - 14) * 30)
            i += 1
    assert abs(previous_end * RATE - frames) <= 1
    events.sort()  # Stable deterministic ordering for simultaneous notes.
    lines = ['/* Generated by tools/compile_music.py from music/prototype.json. */',
             f'#define SYNTH_SCORE_FRAMES {frames}u', 'static const SynthEvent synth_score[] = {']
    lines += ['    {' + ','.join(map(str, e)) + '},' for e in events]
    lines += ['};', '']
    return '\n'.join(lines), len(events)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content, count = generate()
    path = ROOT / 'src/synth_score.inc'
    if args.check:
        if path.read_text() != content:
            raise SystemExit('Synth score stale; run python tools/compile_music.py')
    else:
        path.write_text(content, encoding='utf-8', newline='\n')
    print(f'PASS: {count} sample-addressed notes; original Stage1 recording duration retained')
