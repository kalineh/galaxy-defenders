"""Import the original particle definitions; --check detects stale generated data."""
import argparse
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def scalar(value):
    value = value.replace("MathHelper.TwoPi", "6.283185307f")
    if not re.fullmatch(r"-?[\d.]+f?", value):
        raise ValueError(value)
    return value


def vector(value):
    constants = {"Vector2.Zero": "{0,0}", "Vector2.One": "{1,1}", "Vector2.UnitY": "{0,1}"}
    if value in constants:
        return constants[value]
    match = re.fullmatch(r"new Vector2\(([^,]+), ([^)]+)\)", value)
    if not match:
        raise ValueError(value)
    return "{" + ",".join(scalar(x) for x in match.groups()) + "}"


def generate():
    source = (ROOT / "legacy/Effects/ParticleEffectDefinitions.cs").read_text()
    blocks = re.findall(r"EParticleType\.(\w+),\s*new SEffectDefinition\(\)\s*\{(.*?)\n\s*\}", source, re.S)
    vectors = "Position PositionVariationCircle PositionVariationBox PositionDelta PositionDeltaVariation Scale ScaleVariation ScaleDelta ScaleDeltaVariation".split()
    scalars = "OutDelta Angle AngleVariation AngleDelta AngleDeltaVariation Alpha AlphaVariation AlphaDelta AlphaDeltaVariation".split()
    colors = {"Color.White": "{255,255,255}", "Color.Black": "{0,0,0}",
              "CEnemy.EnemyOrangeColor": "{252,124,85}", "CEnemy.EnemyGrayColor": "{102,102,102}"}
    enum = lambda name: "PARTICLE_" + re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()
    out = ["/* Generated by tools/import_effects.py. */", "#ifndef GALAXY_EFFECTS_DATA_H", "#define GALAXY_EFFECTS_DATA_H", "typedef enum {"]
    out += ["    " + enum(name) + "," for name, _ in blocks]
    out += ["    PARTICLE_COUNT", "} ParticleKind;", "typedef struct {", "    int count, triangle;"]
    out += ["    float " + field + "[2];" for field in vectors]
    out += ["    float " + field + ";" for field in scalars]
    out += ["    unsigned char color[3];", "    int lifetime, variation;", "} ParticleDefinition;", "#ifdef GALAXY_EFFECTS_IMPLEMENTATION", "static const ParticleDefinition particle_definitions[] = {"]
    for name, block in blocks:
        values = dict(re.findall(r"^\s*(\w+) = (.*),\s*$", block, re.M))
        expected = set(vectors + scalars + ["Type", "Count", "Visual", "Color", "Lifetime", "LifetimeVariation"])
        if set(values) != expected:
            raise ValueError((name, set(values) ^ expected))
        row = [values["Count"], "1" if values["Visual"].endswith("Triangle") else "0"]
        row += [vector(values[field]) for field in vectors]
        row += [scalar(values[field]) for field in scalars]
        row += [colors[values["Color"]], values["Lifetime"], values["LifetimeVariation"]]
        out.append("    [" + enum(name) + "] = {" + ",".join(row) + "},")
    out += ["};", "#endif", "#endif", ""]
    return "\n".join(out)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = ROOT / "src/effects_data.h"
    content = generate()
    if args.check:
        if output.read_text() != content:
            raise SystemExit("Particle definitions are stale")
    else:
        output.write_bytes(content.encode())
    print("Particle definitions verified" if args.check else "Particle definitions imported")
