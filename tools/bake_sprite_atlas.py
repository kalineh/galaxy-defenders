"""Bake gameplay sprites. Offline dependencies: Pillow and resvg-py."""
from io import BytesIO
from pathlib import Path
from xml.etree import ElementTree
from PIL import Image, ImageFilter
from resvg_py import svg_to_bytes
from sprite_material import finish_sprite

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "art/sprites"
OUTPUT = ROOT / "assets/textures/atlas"
SHIPS = {"Ace", "Rookie", "Eagle", "Crusher", "Interceptor", "Phoenix", "Lightning", "Dragon", "Demon"}


def dimensions(path):
    if path.suffix == ".svg":
        attrs = ElementTree.parse(path).getroot().attrib
        return int(attrs["width"]), int(attrs["height"])
    with Image.open(path) as image:
        return image.size


def render(path, width, height):
    if path.suffix == ".svg":
        png = svg_to_bytes(svg_path=str(path), width=2*width, height=2*height)
        image = Image.open(BytesIO(png))
    else:
        image = Image.open(path)
    sprite = image.convert("RGBA").resize((width, height), Image.Resampling.LANCZOS)
    alpha = sprite.getchannel("A")
    rgb = sprite.convert("RGB")
    border = rgb.filter(ImageFilter.MaxFilter(3))
    border.paste(rgb, mask=alpha.point(lambda a: 255 if a else 0))
    border.putalpha(alpha)
    return border


def pack(paths, software, modern=False):
    pages, entries = [], []
    for group in ("Flight", "Structures"):
        items = []
        for path in paths:
            rel = path.relative_to(ART)
            if (rel.parts[0] == "stage") != (group == "Structures"):
                continue
            w,h = dimensions(path)
            logical_width = 80 if rel.parent == Path(".") and path.stem in SHIPS else w
            scale = (1 if software else 2)*logical_width/w
            width,height = round(w*scale),round(h*scale)
            sprite = render(path,width,height)
            if modern:
                sprite = finish_sprite(sprite,rel,1 if software else 2,SHIPS)
            # Animation frames are addressed within the logical sheet.
            box = (0,0,width,height) if path.stem in ("Spike","FenceBeam") else sprite.getchannel("A").getbbox()
            if not box:
                box = (0,0,1,1)
            cropped = sprite.crop(box)
            items.append((cropped.height,cropped.width,rel.as_posix(),w,h,width,height,box,cropped))
        # Large sprites first; each shelf is shared by sprites of similar height.
        limit = 2048 if software else 4096
        x = y = shelf = 0
        packed = []
        for height,width,key,w,h,full_w,full_h,box,image in sorted(items,reverse=True):
            if x + width + 8 > limit:
                x,y,shelf = 0,y+shelf,0
            if y + height + 8 > limit:
                pages.append((group,packed))
                x = y = shelf = 0
                packed = []
            packed.append((x+4,y+4,width,height,image))
            entries.append((str(Path(key).with_suffix(".png")).replace("\\","/"),len(pages),x+4,y+4,width,height,w,h,box[0]/full_w,box[1]/full_h,width/full_w,height/full_h))
            x += width+8
            shelf = max(shelf,height+8)
        pages.append((group,packed))
    names = []
    for i,(group,packed) in enumerate(pages):
        width = max(x+w+4 for x,y,w,h,p in packed)
        height = max(y+h+4 for x,y,w,h,p in packed)
        page = Image.new("RGBA", (width,height))
        for x,y,w,h,image in packed:
            if group == "Structures":
                # Clamp the atlas sampler to each tile at its edges, including mip levels.
                # Grow the border into the existing gutter without moving its UVs.
                for left,right,dx,dw in ((0,1,-4,4),(0,w,0,w),(w-1,w,w,4)):
                    for top,bottom,dy,dh in ((0,1,-4,4),(0,h,0,h),(h-1,h,h,4)):
                        if dx == 0 and dy == 0:
                            continue
                        edge = image.crop((left,top,right,bottom))
                        page.paste(edge.resize((dw,dh),Image.Resampling.NEAREST),(x+dx,y+dy))
            page.paste(image,(x,y))
        name = f"{group}{i}{'Modern' if modern else ''}{'Preview' if software else ''}.png"
        page.save(OUTPUT / name)
        names.append(name)
    array = "modern_atlas_files" if modern else "atlas_files"
    lines = [f"static const char *const {array}[] = {{"]
    lines += [f'    "textures/atlas/{name}",' for name in names]
    if modern:
        return lines + ["};"]
    lines += ["};","static const AtlasEntry atlas_entries[] = {"]
    lines += [f'    {{"textures/{key}", {page}, {{{x},{y},{w},{h}}}, {lw},{lh}, {{{ox:.8f}f,{oy:.8f}f,{sx:.8f}f,{sy:.8f}f}}}},'
              for key,page,x,y,w,h,lw,lh,ox,oy,sx,sy in sorted(entries)]
    return lines + ["};"]


def main():
    OUTPUT.mkdir(exist_ok=True)
    paths = sorted(p for p in ART.rglob("*") if p.suffix in (".svg",".png"))
    lines = ["/* Generated by tools/bake_sprite_atlas.py. */","#ifdef GALAXY_MEMORY"]
    lines += pack(paths, True) + pack(paths, True, True) + ["#else"]
    lines += pack(paths, False) + pack(paths, False, True) + ["#endif"]
    (ROOT / "src/sprite_regions.inc").write_bytes(("\n".join(lines)+"\n").encode())


if __name__ == "__main__":
    main()
