"""Bake the gameplay sample atlas. Offline dependencies: Pillow and resvg-py."""
from io import BytesIO
from pathlib import Path

from PIL import Image, ImageFilter
from resvg_py import svg_to_bytes

ROOT = Path(__file__).resolve().parents[1]
# Each region retains the full original canvas so its pivot survives packing.
REGIONS = [
    ("Rookie", 8, 8, 640, 680, 856, 80),
    ("Airship", 664, 8, 320, 680, 680, 160),
    ("SmallBuilding3", 664, 344, 320, 856, 680, 80),
    ("Turret", 8, 680, 320, 856, 776, 80),
    ("Ball", 344, 680, 320, 856, 872, 80),
]


def main():
    atlas = Image.new("RGBA", (1024, 1024))
    header = ["/* Generated by tools/bake_sprite_atlas.py. */"]
    for name, x, y, size, small_x, small_y, logical_size in REGIONS:
        path = ROOT / "art/sprites" / f"{name}.svg"
        png = svg_to_bytes(svg_path=str(path), width=size*2, height=size*2)
        master = Image.open(BytesIO(png)).convert("RGBA")
        for left, top, width in ((x, y, size), (small_x, small_y, logical_size)):
            sprite = master.resize((width, width), Image.Resampling.LANCZOS)
            # Extend silhouette colors into transparent texels for bilinear sampling.
            alpha = sprite.getchannel("A")
            rgb = sprite.convert("RGB")
            border = rgb.filter(ImageFilter.MaxFilter(5))
            border.paste(rgb, mask=alpha.point(lambda a: 255 if a else 0))
            border.putalpha(alpha)
            atlas.paste(border, (left, top))
        header.extend([
            "#ifdef GALAXY_MEMORY",
            f"static const Rectangle atlas_{name.lower()} = {{{small_x},{small_y},{logical_size},{logical_size}}};",
            "#else",
            f"static const Rectangle atlas_{name.lower()} = {{{x},{y},{size},{size}}};",
            "#endif",
        ])
    atlas.save(ROOT / "assets/textures/FlightSprites.png")
    (ROOT / "src/sprite_regions.inc").write_bytes(("\n".join(header) + "\n").encode())


if __name__ == "__main__":
    main()
